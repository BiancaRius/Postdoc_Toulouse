# 4.2. FIX: Patch for typo in transpiration output
# ============================================================
# Problem:
# Some outputs were written as "transpitation" instead of "transpiration".
# This prevents plotting all scenarios together because the variable names
# do not match across scenarios.
#
# Solution:
# 1. Rename "transpitation" to "transpiration" wherever it appears.
# 2. If variables are stored as "transpitation_0", "transpitation_1", etc.,
#    extract the layer number and move them into the layer-level dataframe.
# 3. Do not hard-code a specific scenario, because the typo may occur in
#    Original code, Deep WT, or Shallow WT.

fix_transpiration_typo <- function(df) {
  
  if (is.null(df)) {
    return(NULL)
  }
  
  if (!"variable" %in% names(df)) {
    return(df)
  }
  
  df %>%
    mutate(
      variable = case_when(
        variable == "transpitation" ~ "transpiration",
        TRUE ~ variable
      )
    )
}


