plot_layer_variable <- function(var_name, plot_title, y_label, filename) {
  
  df_plot <- df_water_balance_annual %>%
    filter(variable == var_name) %>%
    mutate(
      layer = factor(
        layer,
        levels = sort(unique(layer))
      )
    )
  
  if (nrow(df_plot) == 0) {
    message("Variable not found in df_water_balance_annual: ", var_name)
    return(NULL)
  }
  
  p <- df_plot %>%
    ggplot(aes(
      x = year,
      y = mean_value,
      color = scenario,
      group = scenario
    )) +
    geom_line(linewidth = 0.7, alpha = 0.7) +
    facet_wrap(~ layer, scales = "free_y", labeller = labeller(layer = function(x) paste("Layer", x))) +
    scale_color_manual(
      values = scenario_colors,
      labels = scenario_labels,
      name = "Scenario"
    ) +
    guides(color = guide_legend(override.aes = list(linewidth = 2, alpha = 1))) +
    labs(
      title = plot_title,
      subtitle = comparison_subtitle,
      x = "Simulation year",
      y = y_label
    ) +
    theme_bw()+
    
    theme(
      panel.grid.minor = element_blank(),
      axis.title = element_text(size = 16), 
      axis.text = element_text(size = 14),  
      legend.title = element_text(size = 16, face = "bold"), 
      legend.text = element_text(size = 14), 
      strip.text = element_text(size = 15, face = "bold"),
      plot.title = element_text(size = 20, face = "bold"),
      plot.subtitle = element_text(size = 16),
    )
  
  save_plot(
    plot_object = p,
    filename = filename,
    width = 10,
    height = 6,
    dpi = 300
  )
  
  return(p)
}


